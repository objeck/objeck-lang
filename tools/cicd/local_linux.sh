#!/usr/bin/env bash
#
# local_linux.sh [REF] [--jit1] [--flags] [--skip-regression] [--skip-libs] [--strict-libs]
#
# Builds and tests the COMMITTED tree (REF, default HEAD) the way ci-build.yml's
# linux-x64 leg does, in a clean copy, so a break shows up before the push rather
# than 30 minutes into the cloud run. Run it inside WSL2 Ubuntu 24.04 (the image
# the runner is pinned to) or on any Linux box with the packages ci-build installs;
# tools/cicd/local_docker.sh runs it in a clean ubuntu:24.04 container.
#
#   * a clean copy from `git archive`: untracked files and local edits cannot hide
#     a missing file, and line endings are the committed ones, as on the runner
#   * deploy_posix.sh x64, the same script CI runs, except that its `make -j3` (sized
#     for a 4-core runner) becomes -j$OBJECK_CI_JOBS in the copy (default: every CPU)
#   * check_docs_deps.py --artifacts: the built tree against runtime_deps.json,
#     the check that failed master CI when ubuntu-latest moved to 26.04 (#1479)
#   * every library compiled from source (core/compiler/build_libs.sh), which must produce
#     the committed core/lib/*.obl: deploy_posix.sh only COPIES the committed files, so
#     without this a library that no longer compiles passes locally and fails in the cloud.
#     A library that fails to compile is an error. A committed .obl that merely LAGS its
#     source (the repo refreshes the set at each version bump) is a warning, because cloud
#     CI rebuilds the libraries and does not require them committed; --strict-libs makes
#     it an error. lang.obl is built by the separate bootstrap compiler and is not rebuilt.
#   * the regression suite, split into $OBJECK_CI_SHARDS processes (default 8) when the
#     tree's run_regression.sh supports REGRESSION_SHARD; with --jit1 again with
#     OBJECK_JIT_THRESHOLD=1
#   * with --flags, run_vm_flag_tests.py
#
# Uncommitted changes are NOT tested: commit first (a throwaway commit is fine).
# The work tree is kept under $OBJECK_CI_WORK (default ~/objeck-ci/<sha>) so a failure
# can be inspected; trees untouched for three hours are pruned.
#
# Do not edit this file while it runs: bash reads a script as it executes it.
set -uo pipefail

REF=HEAD
JIT1=0
FLAGS=0
REGRESSION=1
LIBS=1
LIBS_STRICT=0
for arg in "$@"; do
  case "$arg" in
    --jit1)            JIT1=1 ;;
    --flags)           FLAGS=1 ;;
    --skip-regression) REGRESSION=0 ;;
    --skip-libs)       LIBS=0 ;;
    --strict-libs)     LIBS_STRICT=1 ;;
    -*)                echo "unknown option: $arg"; exit 2 ;;
    *)                 REF="$arg" ;;
  esac
done

case "$(uname -s)" in
  Linux) ;;
  *) echo "local_linux.sh builds the Linux leg: run it inside WSL2 Ubuntu or on Linux"; exit 2 ;;
esac

JOBS="${OBJECK_CI_JOBS:-$(nproc)}"
SHARDS="${OBJECK_CI_SHARDS:-8}"

# A git worktree's .git file names its repository by a Windows path, which Linux git cannot
# follow: use the Windows git through WSL interop then (found by a parallel worker).
if [ -f .git ] && grep -q '^gitdir: [A-Za-z]:' .git && command -v git.exe >/dev/null 2>&1; then
  g() { git.exe "$@"; }
else
  g() { git -c safe.directory='*' "$@"; }
fi
sha=$(g rev-parse --short "$REF" | tr -d '') || exit 2
base="${OBJECK_CI_WORK:-$HOME/objeck-ci}"
work="$base/$sha"

echo "== local linux-x64 leg: $REF ($sha), $JOBS build jobs, $SHARDS regression shards"
if [ -n "$(g status --porcelain --untracked-files=no 2>/dev/null)" ]; then
  echo "   note: the working tree has uncommitted changes; only $sha is tested"
fi

rm -rf "$work"
mkdir -p "$work"
g archive "$REF" | tar -x -C "$work" || exit 2
# Drop trees untouched for three hours. Not 'the newest three': with several runs at once
# that deleted a run's own tree under it. A running leg writes its logs constantly, so its
# tree stays fresh; set OBJECK_CI_WORK to a private directory per worker to be safe.
find "$base" -mindepth 1 -maxdepth 1 -type d -mmin +180 -exec rm -rf {} + 2>/dev/null || true

# More build jobs than the runner's 4 cores: the only change made to the copy.
sed -i "s/-j3\b/-j$JOBS/g" "$work/core/release/deploy_posix.sh"

# ci-build.yml gives the regression suite an in-memory SQLite ODBC data source and sets
# OBJECK_REQUIRE_ODBC so an ODBC test that cannot open it FAILS rather than printing SKIP.
# Do the same when the SQLite driver is installed (libsqliteodbc); otherwise say that the
# ODBC tests will skip, so a green run here is not read as covering them.
if command -v odbcinst >/dev/null 2>&1 && odbcinst -q -d 2>/dev/null | grep -q '^\[SQLite3\]'; then
  if ! grep -qs '^\[objeck_sqlite_test\]' "$HOME/.odbc.ini"; then
    printf '[objeck_sqlite_test]\nDescription=Objeck ODBC regression test DSN\nDriver=SQLite3\nDatabase=:memory:\n' >> "$HOME/.odbc.ini"
  fi
  export OBJECK_REQUIRE_ODBC=1
else
  echo "   note: no SQLite ODBC driver (apt install libsqliteodbc): the ODBC regression tests will skip"
fi

FAIL=0
step() { printf '\n== %s\n' "$*"; }
bad()  { echo "   FAIL: $*"; FAIL=1; }

# run_suite LABEL [VAR=value ...]: the regression suite, sharded when the tree supports it.
# Prints the summed totals and returns non-zero when any test failed.
run_suite() {
  local label=$1; shift
  local dir="$work/programs/regression"
  if [ "$SHARDS" -gt 1 ] && grep -q REGRESSION_SHARD "$dir/run_regression.sh"; then
    local pids=() i
    for ((i = 0; i < SHARDS; i++)); do
      ( cd "$dir" && env "$@" REGRESSION_SHARD="$i/$SHARDS" ./run_regression.sh x64 ) > "$work/${label}_shard$i.log" 2>&1 &
      pids+=($!)
    done
    for p in "${pids[@]}"; do wait "$p" || true; done
    cat "$work/${label}"_shard*.log > "$work/$label.log"
  else
    ( cd "$dir" && env "$@" ./run_regression.sh x64 ) > "$work/$label.log" 2>&1
  fi
  grep -h '\[FAIL\]' "$work/$label.log" | head -10
  awk '/Results:/ { p += $2; s += $4; f += $6 } END { printf "   %d passed, %d skipped, %d failed\n", p, s, f; exit (f > 0 || NR == 0) }' "$work/$label.log"
}

# obr links HTTP/2 and HTTP/3 statically; CI builds those libraries first (the quic-deps
# action). A no-op when the prefix (~/objeck-deps/linux-x86_64) already holds this version.
step "QUIC dependencies (tools/deps/build_quic_deps.sh)"
start=$(date +%s)
if ( cd "$work" && bash tools/deps/build_quic_deps.sh ) > "$work/quic_deps.log" 2>&1; then
  echo "   ok after $(( $(date +%s) - start )) s"
else
  tail -25 "$work/quic_deps.log"
  bad "the QUIC dependencies did not build"
  exit 1
fi

step "build (deploy_posix.sh x64)"
start=$(date +%s)
( cd "$work/core/release" && sh ./deploy_posix.sh x64 ) > "$work/build.log" 2>&1
rc=$?
echo "   exit $rc after $(( $(date +%s) - start )) s, log: $work/build.log"
if [ "$rc" -ne 0 ] || [ ! -x "$work/core/release/deploy/bin/obr" ]; then
  tail -25 "$work/build.log"
  bad "the build failed"
  exit 1
fi

step "built tree vs runtime_deps.json"
( cd "$work" && python3 tools/cicd/check_docs_deps.py --artifacts core/release/deploy --platform linux-x64 ) \
  || bad "the built tree links libraries runtime_deps.json does not list (or the reverse)"

if [ "$LIBS" -eq 1 ]; then
  step "libraries compile from source and equal the committed .obl"
  start=$(date +%s)
  rm -rf "$work/committed_obl"; mkdir -p "$work/committed_obl"
  cp "$work"/core/lib/*.obl "$work/committed_obl/"
  if ( cd "$work/core/compiler" && sh ./build_libs.sh ./obc ) > "$work/libs.log" 2>&1; then
    differ=0
    for f in "$work"/committed_obl/*.obl; do
      n=$(basename "$f")
      [ "$n" = lang.obl ] && continue
      if ! cmp -s "$f" "$work/core/lib/$n"; then echo "   differs from the committed copy: $n"; differ=1; fi
    done
    if [ "$differ" -eq 0 ]; then
      echo "   $(ls "$work"/committed_obl/*.obl | wc -l) libraries rebuilt, identical to the committed set ($(( $(date +%s) - start )) s)"
    elif [ "$LIBS_STRICT" -eq 1 ]; then
      bad "a committed .obl lags its source (rebuild with core/compiler/update_version.sh and commit it)"
    else
      echo "   warning: the libraries above lag their source; the set is refreshed at each version bump (--strict-libs fails on this)"
    fi
  else
    tail -20 "$work/libs.log"
    bad "a library does not compile from source: $work/libs.log"
  fi
fi

if [ "$REGRESSION" -eq 1 ]; then
  step "regression"
  start=$(date +%s)
  run_suite regression || bad "regression had failures: $work/regression.log"
  echo "   $(( $(date +%s) - start )) s"

  if [ "$JIT1" -eq 1 ]; then
    step "regression, OBJECK_JIT_THRESHOLD=1"
    start=$(date +%s)
    run_suite regression_jit1 OBJECK_JIT_THRESHOLD=1 || bad "JIT-threshold-1 regression had failures: $work/regression_jit1.log"
    echo "   $(( $(date +%s) - start )) s"
  fi
fi

if [ "$FLAGS" -eq 1 ]; then
  step "run_vm_flag_tests.py"
  ( cd "$work/programs/regression" && python3 run_vm_flag_tests.py "$work/core/release/deploy/bin" ) > "$work/flags.log" 2>&1
  flags_rc=$?
  grep -c '\[PASS\]' "$work/flags.log" | sed 's/^/   passed: /'
  grep '\[FAIL\]' "$work/flags.log" | head -10
  grep -q '\[FAIL\]' "$work/flags.log" && bad "flag tests had failures: $work/flags.log"
  # The exit status counts too: a traceback or a crash part-way through prints no [FAIL] line,
  # and a merge once left the script dying with a NameError after section 31 while this leg
  # still reported a pass.
  if [ "$flags_rc" -ne 0 ]; then
    tail -5 "$work/flags.log"
    bad "run_vm_flag_tests.py exited $flags_rc: $work/flags.log"
  fi
  grep -q '^Traceback' "$work/flags.log" && bad "run_vm_flag_tests.py raised: $work/flags.log"
fi

echo
if [ "$FAIL" -eq 0 ]; then
  echo "LOCAL LINUX LEG PASSES for $sha"
else
  echo "LOCAL LINUX LEG FAILED for $sha (tree kept: $work)"
fi
exit "$FAIL"
