# Signs every .msi in a folder with the SafeNet token WITHOUT the interactive "Token Logon" prompt,
# reading the token password from the DPAPI-protected file made by token_pin.ps1.
#
#   sign_with_saved_pin.ps1 -Dir <folder> [-ManifestFile SHA256SUMS] [-WhatIf]
#
# Exit 0 = every installer is signed (or already was). Non-zero = something refused or failed; the message
# says which. On a SIGNING failure it also writes <PinFile folder>\signing_failed.txt and refuses to run again
# until that file is deleted: a wrong or locked token must be looked at by a person, because SafeNet tokens
# LOCK after a few wrong passwords and a scheduled retry loop would do exactly that.
#
# How the password is passed: signtool has no "read the password from a file" switch. The supported
# unattended form for a SafeNet eToken is the key-container syntax  /csp <provider> /k "[{{PASSWORD}}]=<container>"
# together with the PUBLIC certificate as a file (/f). That puts the password on signtool's command line for the
# few seconds it runs, where other processes of the same user could read it. It is never printed, logged or
# written anywhere by this script; it is held in memory only and cleared afterwards.
#
# The certificate thumbprint and container name are those of CN=Randy Hollines (Sectigo, expires 2028-05-25),
# the same ones sign_release.cmd uses. On renewal, update both (the container is the "Key Container" line of
#   certutil -user -store My <thumbprint>   -- run that with the token plugged in).
param(
    [Parameter(Mandatory = $true)][string]$Dir,
    [string]$ManifestFile = '',
    [string]$Thumbprint = '6DEAD3A9C58C82DD3CE979DBDFAF64CC964C0A46',
    [string]$Container = 'Sectigo_20250526125150',
    [string]$Provider = 'eToken Base Cryptographic Provider',
    [string]$Timestamp = 'http://timestamp.sectigo.com',
    [string]$PinFile = (Join-Path $env:USERPROFILE '.objeck\token_pin.dpapi'),
    [string]$SignTool = 'C:\Program Files (x86)\Windows Kits\10\bin\10.0.26100.0\x64\signtool.exe',
    [switch]$WhatIf
)

$ErrorActionPreference = 'Stop'
function Fail([string]$m) { Write-Host "ERROR: $m"; exit 1 }

$stateDir = Split-Path -Parent $PinFile
$failMarker = Join-Path $stateDir 'signing_failed.txt'

if (Test-Path -LiteralPath $failMarker) {
    Fail "an earlier signing attempt failed ($failMarker). Not trying again automatically: a wrong password can lock the token. Check the token, then delete that file."
}
if (-not (Test-Path -LiteralPath $PinFile)) { Fail "no saved password file ($PinFile). Create it with tools\cicd\token_pin.ps1 -Set" }
if (-not (Test-Path -LiteralPath $SignTool)) { Fail "signtool not found: $SignTool" }
if (-not (Test-Path -LiteralPath $Dir)) { Fail "folder not found: $Dir" }

$msis = @(Get-ChildItem -LiteralPath $Dir -Filter *.msi)
if ($msis.Count -eq 0) { Fail "no .msi files in $Dir" }

# ---- integrity: what we are about to sign must be what CI built ------------------------------------
# SHA256SUMS is generated by the release workflow BEFORE signing and covers the MSIs. A mismatch means
# the asset on the release is not the one the build produced, and an unattended signer must not put the
# company certificate on it.
if ($ManifestFile) {
    if (-not (Test-Path -LiteralPath $ManifestFile)) { Fail "manifest not found: $ManifestFile" }
    $want = @{}
    foreach ($line in Get-Content -LiteralPath $ManifestFile) {
        if ($line -match '^([0-9a-fA-F]{64})\s+\*?(.+?)\s*$') { $want[$Matches[2]] = $Matches[1].ToLower() }
    }
    foreach ($m in $msis) {
        $got = (Get-FileHash -LiteralPath $m.FullName -Algorithm SHA256).Hash.ToLower()
        if (-not $want.ContainsKey($m.Name)) { Fail "$($m.Name) is not listed in SHA256SUMS: refusing to sign an unlisted file" }
        # an installer already signed by us was re-listed after signing, so it still matches; anything else must match the CI hash
        if ($want[$m.Name] -ne $got) { Fail "$($m.Name) does not match SHA256SUMS (the release asset differs from what CI built): refusing to sign" }
    }
    Write-Host "Integrity: $($msis.Count) installer(s) match SHA256SUMS."
}

# ---- already signed by this certificate? skip ----------------------------------------------------------
$todo = @()
foreach ($m in $msis) {
    $sig = Get-AuthenticodeSignature -LiteralPath $m.FullName
    if ($sig.Status -eq 'Valid' -and $sig.SignerCertificate -and $sig.SignerCertificate.Thumbprint -eq $Thumbprint) {
        Write-Host "Already signed: $($m.Name)"
    } else { $todo += $m }
}
if ($todo.Count -eq 0) { Write-Host 'Nothing to sign.'; exit 0 }

# ---- the public certificate (no secret in it) ---------------------------------------------------------
$cert = Get-Item -LiteralPath "Cert:\CurrentUser\My\$Thumbprint" -ErrorAction SilentlyContinue
if (-not $cert) { Fail "certificate $Thumbprint is not in Cert:\CurrentUser\My (is the token plugged in and its client running?)" }
$cer = Join-Path $env:TEMP "objeck-sign-$([guid]::NewGuid().ToString('N')).cer"
[void](Export-Certificate -Cert $cert -FilePath $cer -Type CERT)

# ---- read the password (memory only) ------------------------------------------------------------------
$bstr = [IntPtr]::Zero
$plain = $null
try {
    $secure = (Get-Content -LiteralPath $PinFile -Raw).Trim() | ConvertTo-SecureString
    $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
    $plain = [Runtime.InteropServices.Marshal]::PtrToStringBSTR($bstr)
} catch {
    Remove-Item -LiteralPath $cer -Force -ErrorAction SilentlyContinue
    Fail "could not decrypt $PinFile. It only opens for the account and machine that created it. Re-create it with token_pin.ps1 -Set"
} finally {
    if ($bstr -ne [IntPtr]::Zero) { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
}

$fixed = @('sign', '/fd', 'SHA256', '/td', 'SHA256', '/tr', $Timestamp, '/f', $cer, '/csp', $Provider)
$files = @($todo | ForEach-Object { $_.FullName })

if ($WhatIf) {
    $shown = $fixed + @('/k', "[{{****}}]=$Container") + $files
    Write-Host 'WHAT IF: password file decrypted OK (value not shown). Would run:'
    Write-Host ('  "' + $SignTool + '" ' + (($shown | ForEach-Object { if ($_ -match '\s') { '"' + $_ + '"' } else { $_ } }) -join ' '))
    Remove-Item -LiteralPath $cer -Force -ErrorAction SilentlyContinue
    $plain = $null
    exit 0
}

$exit = 1
try {
    $args2 = $fixed + @('/k', "[{{$plain}}]=$Container") + $files
    $out = & $SignTool @args2 2>&1
    $exit = $LASTEXITCODE
} finally {
    $plain = $null
    $args2 = $null
    Remove-Item -LiteralPath $cer -Force -ErrorAction SilentlyContinue
}

if ($exit -ne 0) {
    # signtool does not echo the password; still, show only its own message lines
    ($out | ForEach-Object { "$_" }) | Select-Object -First 12 | ForEach-Object { Write-Host "  signtool: $_" }
    "$(Get-Date -Format s)  signtool exit $exit on: $($todo.Name -join ', ')" | Set-Content -LiteralPath $failMarker
    Fail "signing failed (signtool exit $exit). Stopped on purpose; wrote $failMarker so nothing retries. Check the token and the saved password."
}
Write-Host "Signed $($todo.Count) installer(s) with the saved token password."
exit 0
