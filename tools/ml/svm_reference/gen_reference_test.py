#!/usr/bin/env python3
"""Write programs/regression/ml_kernel_svm_reference.obs.

Draws small random problems (four per kernel, convex ones only), solves each
with the references in svm_reference.py -- the exact KKT enumeration where n is
tiny, otherwise the first-order SMO at tol 1e-10 -- and bakes the data, the
reference dual objective and reference decision values into a regression test,
so CI checks KernelSVM against an independent solver without Python.

Usage: python gen_reference_test.py [--seed N] [--out PATH]
"""
import argparse
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import svm_reference as R  # noqa: E402

KERNEL_ENUM = ["LINEAR", "RBF", "POLY", "SIGMOID"]


def lit(v):
    s = repr(float(v))
    if "e" in s or "E" in s:
        # Objeck float literals take no exponent: write it out positionally.
        s = np.format_float_positional(float(v), trim="0", precision=25)
        if s.endswith("."):
            s += "0"
    if "." not in s:
        s += ".0"
    return s


def problem(rng, code, idx):
    while True:
        tiny = idx % 2 == 0
        n = int(rng.integers(5, 8)) if tiny else int(rng.integers(12, 31))
        d = int(rng.integers(1, 5))
        if code == 3:
            # tanh(gamma x.z) is PSD only when the Gram matrix x.z has room to
            # spare, so sigmoid problems get more features than rows
            n = int(rng.integers(5, 11))
            tiny = n <= 7
            d = n + 4
        pr = R.make_problem(rng, idx, code, n, 6, d, tiny, False)
        if code == 3:
            # the sigmoid kernel is PSD-ish only near its linear regime
            pr["coef0"] = 0.0
            pr["gamma"] = 0.02 / d
            pr["C"] = min(pr["C"], 10.0)
        x = pr["x"]
        y = np.where(pr["y"], 1.0, -1.0)
        K = R.kernel_matrix(x, x, code, pr["gamma"], pr["degree"], pr["coef0"])
        eig = np.linalg.eigvalsh(K)
        if eig.min() < -1e-9 * max(1.0, eig.max()):
            continue  # a non-convex sigmoid draw: try again
        Q = (y[:, None] * y[None, :]) * K
        C = np.full(n, pr["C"])
        p = -np.ones(n)
        if tiny:
            a, obj = R.exact_reference(Q, y, C, p)
            source = "exact enumeration"
        else:
            try:
                a, _ = R.smo_reference(Q, y, C, p, max_iter=300000)
            except RuntimeError:
                continue  # first-order SMO stalls on some ill-conditioned draws
            obj = 0.5 * a @ Q @ a + p @ a
            source = "first-order SMO"
        G = Q @ a + p
        rho = R.rho_of(a, G, y, C)
        Kt = R.kernel_matrix(pr["t"], x, code, pr["gamma"], pr["degree"], pr["coef0"])
        f = Kt @ (a * y) - rho
        return pr, obj, f, source


def emit(out, problems):
    w = out.write
    w("# EXTRA_LIBS: ml,gen_collect,csv\n")
    w("#~\nKernelSVM against an independent reference, without Python.\n\n")
    w("Generated by tools/ml/svm_reference/gen_reference_test.py: small random problems,\n")
    w("four per kernel, each solved by the exact KKT enumeration (n <= 7) or by a\n")
    w("plain first-order SMO run to 1e-10 -- neither shares code with the solver in\n")
    w("ml_svm.obs. KernelSVM, fitted at tol 1e-9, must reach the reference's dual\n")
    w("objective to 1e-6 (relative, floor 1) and its decision values on six unseen\n")
    w("rows to 1e-5. The full comparison (272 problems, support sets, KKT) is\n")
    w("svm_reference.py; this is the part CI can run.\n\n")
    w("Labels are Int literals converted to Bool, because Bool array literals are\n")
    w("unreliable in large methods; each problem is its own method for the same reason.\n~#\n")
    w("use System.ML;\n\nclass MlKernelSvmReference {\n")
    w("\tfunction : Main(args : String[]) ~ Nil {\n\t\tok := true;\n")
    for i, _ in enumerate(problems):
        w("\t\tok := Problem%d() & ok;\n" % i)
    w("\n\t\tif(<>ok) {\n\t\t\tRuntime->Exit(1);\n\t\t};\n\t}\n\n")
    for i, (pr, obj, f, source) in enumerate(problems):
        x = pr["x"]
        w("\t# %s, n=%d, d=%d, C=%s, gamma=%s, degree=%d, coef0=%s; reference: %s\n" % (
            KERNEL_ENUM[pr["code"]].lower(), pr["n"], pr["d"], lit(pr["C"]), lit(pr["gamma"]),
            pr["degree"], lit(pr["coef0"]), source))
        w("\tfunction : Problem%d() ~ Bool {\n" % i)
        w("\t\tx := [\n")
        w(",\n".join("\t\t\t[" + ", ".join(lit(v) for v in row) + "]" for row in x))
        w("];\n")
        w("\t\tlabels := [" + ", ".join("1" if v else "0" for v in pr["y"]) + "];\n")
        w("\t\tt := [\n")
        w(",\n".join("\t\t\t[" + ", ".join(lit(v) for v in row) + "]" for row in pr["t"]))
        w("];\n")
        w("\t\texpected := [" + ", ".join(lit(v) for v in f) + "];\n")
        w("\t\treturn Check(\"%s #%d\", x, labels, t, SvmKernel->%s, %s, %s, %d, %s, %s, expected);\n" % (
            KERNEL_ENUM[pr["code"]].lower(), i, KERNEL_ENUM[pr["code"]], lit(pr["C"]),
            lit(pr["gamma"]), pr["degree"], lit(pr["coef0"]), lit(obj)))
        w("\t}\n\n")
    w(CHECK)
    w("}\n")


CHECK = """\tfunction : Check(name : String, x : Float[,], labels : Int[], t : Float[,], kernel : SvmKernel,
			c : Float, gamma : Float, degree : Int, coef0 : Float, objective : Float, expected : Float[]) ~ Bool {
		y := Bool->New[labels->Size()];
		each(i : labels) {
			y[i] := labels[i] = 1;
		};

		svm := KernelSVM->New(kernel, c, gamma, degree, coef0);
		svm->SetTolerance(0.000000001);
		if(<>svm->Fit(x, y)) {
			error := svm->GetLastError();
			"FAIL: {$name}: Fit failed: {$error}"->PrintLine();
			return false;
		};

		got := svm->GetObjective();
		scale := objective->Abs();
		if(scale < 1.0) {
			scale := 1.0;
		};
		if((got - objective)->Abs() > 0.000001 * scale) {
			"FAIL: {$name}: objective {$got}, reference {$objective}"->PrintLine();
			return false;
		};

		f := svm->DecisionFunction(t);
		diff := 0.0;
		want := 0.0;
		each(i : expected) {
			want := expected[i];
			diff := (f[i] - want)->Abs();
			if(diff > 0.00001 * (1.0 + want->Abs())) {
				have := f[i];
				"FAIL: {$name}: decision value {$i} is {$have}, reference {$want}"->PrintLine();
				return false;
			};
		};

		"PASS: {$name}: objective and decision values match the reference"->PrintLine();
		return true;
	}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7031)
    here = os.path.dirname(os.path.abspath(__file__))
    ap.add_argument("--out", default=os.path.join(here, "..", "..", "..", "programs",
                                                  "regression", "ml_kernel_svm_reference.obs"))
    args = ap.parse_args()
    rng = np.random.default_rng(args.seed)
    problems = []
    for code in range(4):
        for k in range(4):
            problems.append(problem(rng, code, len(problems)))
    with open(args.out, "w", newline="\n") as fh:
        emit(fh, problems)
    print("wrote %s (%d problems)" % (os.path.normpath(args.out), len(problems)))


if __name__ == "__main__":
    main()
