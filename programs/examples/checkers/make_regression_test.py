#!/usr/bin/env python3
"""Build programs/regression/checkers_engine.obs from the example's own files.

The regression runners compile ONE .obs file per test, so a test cannot name the
other source files it needs. The checkers example is several files (engine, game,
players, window logic, music, tests) that are compiled together with
`obc -src a.obs,b.obs,...`; this script joins the headless ones and the tests into
the single file the regression runners want, hoisting every `use` line to the top.

The regression file is generated, never edited: change the files in this folder and
run

    python3 programs/examples/checkers/make_regression_test.py          # rewrite it
    python3 programs/examples/checkers/make_regression_test.py --check  # CI: fail if stale

so the suite always runs exactly what the example ships.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, "..", "..", "regression", "checkers_engine.obs"))

# order matters only for readability: the compiler resolves classes across the file
PARTS = [
    "checkers_engine.obs",
    "checkers_game.obs",
    "checkers_ai.obs",
    "checkers_logic.obs",
    "checkers_music.obs",
    "checkers_tests.obs",
]

HEADER = """# EXTRA_LIBS: ai
# GENERATED by programs/examples/checkers/make_regression_test.py from the checkers_*.obs
# files next to it. Do not edit this file: edit those and run the script again
# (tools/cicd/check_checkers_test.py fails when this file is out of date).
# Headless: no window, no sound, no files other than one small settings file.
"""

USE = re.compile(r"^use\s+[\w.]+;\s*$")


def build():
    uses = []
    bodies = []
    for name in PARTS:
        path = os.path.join(HERE, name)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8", newline="") as f:
            text = f.read().replace("\r\n", "\n")
        body = []
        for line in text.split("\n"):
            if USE.match(line):
                if line.strip() not in uses:
                    uses.append(line.strip())
            else:
                body.append(line)
        bodies.append("# ---- %s ----\n" % name + "\n".join(body).strip("\n") + "\n")
    return HEADER + "\n" + "\n".join(uses) + "\n\n" + "\n".join(bodies)


def main(argv):
    text = build()
    if "--check" in argv:
        current = ""
        if os.path.exists(OUT):
            with open(OUT, encoding="utf-8", newline="") as f:
                current = f.read().replace("\r\n", "\n")
        if current != text:
            print("programs/regression/checkers_engine.obs is out of date; run "
                  "python3 programs/examples/checkers/make_regression_test.py")
            return 1
        print("programs/regression/checkers_engine.obs matches the checkers example sources")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote " + OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
