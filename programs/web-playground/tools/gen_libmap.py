#!/usr/bin/env python3
"""Regenerate backend/app/services/libmap_data.json.

The playground infers which libraries a program needs from its `use` statements.
That needs two facts the compiler keeps in separate places:

  * which bundles (and public classes) each library declares -- the
    `bundle X { ... }` blocks in core/compiler/lib_src/*.obs, and
  * which other libraries each one must be linked with -- the `-lib` list each
    library is built with in core/compiler/build_libs.sh. The linker loads exactly
    what it is given and does not chase a library's own dependencies, so the
    playground has to supply the whole closure itself.

This script reads both and writes one JSON file. It is the single source of truth:
nothing in the backend hard-codes a bundle name. backend/tests/test_libmap.py fails
when the committed JSON is stale, so a new library or bundle cannot ship unmapped.

Usage (from anywhere):  python programs/web-playground/tools/gen_libmap.py [--check]
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend"))
from app.services.source_scan import scan  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
COMPILER = REPO / "core" / "compiler"
OUT = Path(__file__).resolve().parents[1] / "backend" / "app" / "services" / "libmap_data.json"

# Libraries the compiler always supplies and strips from any user -lib
# (compiler.cpp: sys_lib_path = "lang,gen_collect").
DEFAULT_LIBS = ["lang", "gen_collect"]


# public class / interface / enum / record / consts declarations; `class : private :`
# and the hidden `$Name` primitives are not part of the API.
_DECL = re.compile(
    r"\b(class|interface|enum|record|consts)\s+(?:(:)\s*(public|private)\s*:\s*)?([A-Za-z_]\w*)"
)
_BUNDLE = re.compile(r"^bundle\s+([\w.]+)\s*\{", re.M)


def scan_source(path: Path) -> dict[str, set[str]]:
    """bundle name -> public type names declared in one .obs file.

    A type is "declared by the bundle" when it sits directly inside the bundle's
    braces. An `enum` inside a class is nested, and a program cannot name it on
    its own, so brace depth (not indentation: libraries mix tabs and spaces) decides.
    """
    # the playground's own lexer: string-aware, so a "#" inside a string is not a comment
    # braces inside "{$x}" must not count, so literals are blanked as well
    text = scan(path.read_text(encoding="utf-8", errors="replace"), blank_literals=True).code

    result: dict[str, set[str]] = {}
    for m in _BUNDLE.finditer(text):
        names = result.setdefault(m.group(1), set())
        depth, i = 1, m.end()
        while i < len(text) and depth > 0:
            c = text[i]
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
            elif depth == 1 and c in "cier":  # cheap filter before the regex
                d = _DECL.match(text, i)
                if d and (i == 0 or not (text[i - 1].isalnum() or text[i - 1] in "_$")):
                    if d.group(3) != "private":
                        names.add(d.group(4))
                    i = d.end()
                    continue
            i += 1
    return result


def build() -> dict:
    libs: dict[str, dict] = {}

    # lang.obl is built separately (needs the _SYSTEM bootstrap compiler)
    lang = scan_source(COMPILER / "lib_src" / "lang.obs")
    libs["lang"] = {"deps": [], "bundles": {b: sorted(c) for b, c in sorted(lang.items())}}

    for line in (COMPILER / "build_libs.sh").read_text().splitlines():
        if "$OBC" not in line or "-src" not in line or "-dest" not in line:
            continue
        sources = re.search(r"-src (\S+)", line).group(1).split(",")
        dest = re.search(r"-dest \.\./lib/(\w+)\.obl", line).group(1)
        dep_match = re.search(r"-lib (\S+)", line)
        deps = [d for d in (dep_match.group(1).split(",") if dep_match else [])
                if d not in ("../lib/lang", "lang")]
        bundles: dict[str, set[str]] = {}
        for src in sources:
            for bundle, names in scan_source(COMPILER / src).items():
                bundles.setdefault(bundle, set()).update(names)
        libs[dest] = {"deps": deps, "bundles": {b: sorted(c) for b, c in sorted(bundles.items())}}

    return {
        "_comment": "GENERATED by programs/web-playground/tools/gen_libmap.py -- do not edit",
        "default_libs": DEFAULT_LIBS,
        "libs": dict(sorted(libs.items())),
    }


def render(data: dict) -> str:
    """One line per bundle keeps the file reviewable (a diff names the bundle)."""
    out = ["{", f' "_comment": {json.dumps(data["_comment"])},',
           f' "default_libs": {json.dumps(data["default_libs"])},', ' "libs": {']
    items = list(data["libs"].items())
    for i, (name, lib) in enumerate(items):
        out.append(f'  {json.dumps(name)}: {{')
        out.append(f'   "deps": {json.dumps(lib["deps"])},')
        out.append('   "bundles": {')
        bundles = list(lib["bundles"].items())
        for j, (bundle, classes) in enumerate(bundles):
            comma = "," if j + 1 < len(bundles) else ""
            out.append(f'    {json.dumps(bundle)}: {json.dumps(classes)}{comma}')
        out.append("   }")
        out.append("  }" + ("," if i + 1 < len(items) else ""))
    out += [" }", "}"]
    return "\n".join(out) + "\n"


def main() -> int:
    text = render(build())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale; run tools/gen_libmap.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
