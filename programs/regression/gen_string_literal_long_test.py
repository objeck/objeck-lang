#!/usr/bin/env python3
"""Writes string_literal_long_test.obs, beside this file: its literals are too long to type.

    python3 gen_string_literal_long_test.py [out.obs]

Change a shape here and run it; the test is committed as written.
"""
import os
import sys


def flat(prefix, n, per=12):
    items = ['"%s%d"' % (prefix, i) for i in range(n)]
    rows = [', '.join(items[i:i + per]) for i in range(0, n, per)]
    return '[\n      ' + ',\n      '.join(rows) + ']'


def two(n_rows):
    rows = ['["r%d_0", "r%d_1"]' % (i, i) for i in range(n_rows)]
    lines = [', '.join(rows[i:i + 5]) for i in range(0, n_rows, 5)]
    return '[\n      ' + ',\n      '.join(lines) + ']'


def three(n):
    rows = ['[' + ', '.join('[' + ', '.join('"c%d_%d_%d"' % (i, j, k) for k in range(3)) + ']' for j in range(2)) + ']'
            for i in range(n)]
    lines = [', '.join(rows[i:i + 2]) for i in range(0, n, 2)]
    return '[\n      ' + ',\n      '.join(lines) + ']'


HEAD = """#~
# String array literals longer than a method's operand stack.
#
# GENERATED by gen_string_literal_long_test.py (the literals are long): change a
# shape there, not a list here.
#
# A String literal used to be built on the operand stack: every element pushed,
# then the array, and one trap (CPY_CHAR_STR_ARYS) to fill it. A method has room
# for about 1,000 words there and the loader refuses one that holds more, so a
# literal of 999 strings in a function without parameters (1,000 in Main) compiled
# and then would not load: ">>> Invalid bytecode: ... the operand stack grows to
# 1001 words past the arguments, more than a call's room <<<". A literal of more
# than 512 strings is now built in a hidden local, an element at a time, as
# '["a", b]' is. Every element of every shape is compared with the text its
# position spells, so a store to the wrong subscript fails here:
#
#   one dimension    512 (the old lowering's longest), 513 (the new one's shortest),
#                    999 in a function without parameters (the case refused), 1,100
#                    in Main, 2,000
#   two dimensions   600 x 2
#   three            200 x 2 x 3
#   in a loop (the hidden local is reused; collections run), as an argument between
#   others, subscripted where it stands, and in a method of an instance
#
# The check itself is checked: counted against the wrong prefix, every element of
# the 1,100 must differ.
~#

class StringLiteralLongTest {
  @failed : static : Bool;

  function : Fail(what : String) ~ Nil {
    @failed := true;
    "  FAIL: {$what}"->PrintLine();
  }

  # how many of a's elements are not prefix + their index
  function : Wrong(a : String[], prefix : String) ~ Int {
    wrong := 0;
    each(i : a) {
      e := String->New(prefix);
      e += i;
      if(a[i] = Nil | <>a[i]->Equals(e)) {
        wrong += 1;
      };
    };
    return wrong;
  }

  function : Flat(name : String, a : String[], prefix : String, size : Int) ~ Nil {
    if(a->Size() <> size) {
      n := a->Size();
      Fail("{$name}: {$n} elements, not {$size}");
      return;
    };
    wrong := Wrong(a, prefix);
    if(wrong <> 0) {
      Fail("{$name}: {$wrong} elements are not where they were written");
    };
  }
"""

HELPERS = """
  function : Pick(before : Int, a : String[], index : Int, after : Int) ~ String {
    return a[index + before - after];
  }

  function : InLoop(round : Int) ~ String[] {
    kept : String[];
    for(i := 0; i < 3; i += 1;) {
      a := @L700@;
      if(i = round % 3) {
        kept := a;
      };
    };
    return kept;
  }

  method : public : FromInstance() ~ String[] {
    return @M600@;
  }

  New() {
  }
"""

MAIN = """
  function : Main(args : String[]) ~ Nil {
    @failed := false;

    a := @S1100@;
    Flat("1,100 in Main", a, "s", 1100);

    # the check can fail: against another prefix every element is wrong
    control := Wrong(a, "x");
    if(control <> 1100) {
      Fail("control: {$control} of 1,100 differ from the wrong text");
    };

    Flat("512, on the stack", Old512(), "p", 512);
    Flat("513, an element at a time", New513(), "q", 513);
    Flat("999 in a function without parameters", Refused999(), "h", 999);
    Flat("2,000", Long2000(), "t", 2000);

    rows := Rows600();
    dims := rows->Size();
    if(dims->Size() <> 2 | dims[0] <> 600 | dims[1] <> 2) {
      Fail("600 x 2: the dimensions");
    }
    else {
      wrong := 0;
      for(i := 0; i < 600; i += 1;) {
        for(j := 0; j < 2; j += 1;) {
          e := "r";
          e += i;
          e += "_";
          e += j;
          if(rows[i, j] = Nil | <>rows[i, j]->Equals(e)) {
            wrong += 1;
          };
        };
      };
      if(wrong <> 0) {
        Fail("600 x 2: {$wrong} elements are not where they were written");
      };
    };

    cube := Cube200();
    dims := cube->Size();
    if(dims->Size() <> 3 | dims[0] <> 200 | dims[1] <> 2 | dims[2] <> 3) {
      Fail("200 x 2 x 3: the dimensions");
    }
    else {
      wrong := 0;
      for(i := 0; i < 200; i += 1;) {
        for(j := 0; j < 2; j += 1;) {
          for(k := 0; k < 3; k += 1;) {
            e := "c";
            e += i;
            e += "_";
            e += j;
            e += "_";
            e += k;
            if(cube[i, j, k] = Nil | <>cube[i, j, k]->Equals(e)) {
              wrong += 1;
            };
          };
        };
      };
      if(wrong <> 0) {
        Fail("200 x 2 x 3: {$wrong} elements are not where they were written");
      };
    };

    # built again and again: the hidden local holds a new array each time
    for(round := 0; round < 40; round += 1;) {
      Flat("700 in a loop", InLoop(round), "l", 700);
    };

    Flat("600 in a method", StringLiteralLongTest->New()->FromInstance(), "m", 600);

    # an argument between others
    picked := Pick(3, @G550@, 540, 2);
    if(<>picked->Equals("g541")) {
      Fail("as an argument: element 541 is '{$picked}'");
    };

    # subscripted where it stands
    one := @U520@[517];
    if(<>one->Equals("u517")) {
      Fail("subscripted: element 517 is '{$one}'");
    };

    if(@failed) {
      "FAIL: long String literals"->PrintLine();
      Runtime->Exit(1);
    };
    "PASS: long String literals"->PrintLine();
  }
}
"""


def function(name, typ, literal):
    return "\n  function : %s() ~ %s {\n    return %s;\n  }\n" % (name, typ, literal)


text = HEAD
text += function("Old512", "String[]", flat("p", 512))
text += function("New513", "String[]", flat("q", 513))
text += function("Refused999", "String[]", flat("h", 999))
text += function("Long2000", "String[]", flat("t", 2000))
text += function("Rows600", "String[,]", two(600))
text += function("Cube200", "String[,,]", three(200))
text += HELPERS.replace("@L700@", flat("l", 700)).replace("@M600@", flat("m", 600))
text += MAIN.replace("@S1100@", flat("s", 1100)).replace("@G550@", flat("g", 550)).replace("@U520@", flat("u", 520))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "string_literal_long_test.obs")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write(text)
