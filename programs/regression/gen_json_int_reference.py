#!/usr/bin/env python3
"""Generates json_int_reference.obs: JsonElement->GetInt() against exact integer arithmetic.

    python3 gen_json_int_reference.py            # rewrite json_int_reference.obs
    python3 gen_json_int_reference.py --check    # exit 1 if the committed file is stale

GetInt() truncates a JSON number toward zero from its digits, and answers 0 when the
result does not fit a signed 64-bit integer. The expected values here come from Python's
unbounded integers, not from floating point and not from the library under test: a number
is mantissa * 10^(exponent - fraction digits), and its truncation is one integer division.

The numbers are random but fixed (the seed is in this file), so the test is the same on
every run. They are drawn to land where the conversion can go wrong: results of 17 to 20
digits around the 64-bit limits, fractions and exponents that cancel, long runs of zeros
on either side of the point, and exponents far larger than the value needs.
"""
import random
import sys
from pathlib import Path

SEED = 20261127
COUNT = 400
INT_MIN = -(2 ** 63)
INT_MAX = 2 ** 63 - 1
OUT = Path(__file__).with_name("json_int_reference.obs")


def expected(text):
    """The exact truncation toward zero of a JSON number, 0 when outside 64 bits."""
    negative = text.startswith("-")
    body = text[1:] if negative else text
    exponent = 0
    for mark in ("e", "E"):
        if mark in body:
            body, exp_text = body.split(mark)
            exponent = int(exp_text)
    whole, _, fraction = body.partition(".")
    mantissa = int(whole + fraction)
    shift = exponent - len(fraction)
    if shift >= 0:
        magnitude = mantissa * 10 ** shift
    else:
        magnitude = mantissa // 10 ** (-shift)
    value = -magnitude if negative else magnitude
    return value if INT_MIN <= value <= INT_MAX else 0


def digits(rng, count, first_nonzero):
    text = "".join(rng.choice("0123456789") for _ in range(count))
    if first_nonzero and text and text[0] == "0":
        text = rng.choice("123456789") + text[1:]
    return text


def spell(rng, significant, point_shift):
    """Writes the digit string 'significant' times 10^point_shift in one of several ways."""
    style = rng.randrange(5)
    sign = "-" if rng.random() < 0.4 else ""
    e = rng.choice("eE")
    if style == 0:
        # d.ddd e N
        exponent = point_shift + len(significant) - 1
        fraction = significant[1:]
        body = significant[0] + ("." + fraction if fraction else "")
        return "{}{}{}{}".format(sign, body, e, exponent)
    if style == 1:
        # ddd e N, with an explicit + now and then
        plus = "+" if point_shift >= 0 and rng.random() < 0.5 else ""
        return "{}{}{}{}{}".format(sign, significant, e, plus, point_shift)
    if style == 2:
        # 0.000ddd e N: zeros after the point that the exponent takes back
        zeros = rng.randrange(0, 30)
        exponent = point_shift + len(significant) + zeros
        return "{}0.{}{}{}{}".format(sign, "0" * zeros, significant, e, exponent)
    if style == 3:
        # ddd000 e -N: zeros before the point that the exponent takes back
        zeros = rng.randrange(0, 30)
        return "{}{}{}{}{}".format(sign, significant, "0" * zeros, e, point_shift - zeros)
    # plain decimal, no exponent, when the shift is small enough to write out
    if -40 <= point_shift <= 0:
        cut = len(significant) + point_shift
        if cut > 0:
            return "{}{}.{}".format(sign, significant[:cut], significant[cut:] or "0")
        return "{}0.{}{}".format(sign, "0" * (-cut), significant)
    return "{}{}{}{}".format(sign, significant, e, point_shift)


def cases():
    rng = random.Random(SEED)
    texts = []
    # the 64-bit limits and their neighbours, each spelled every way
    for limit in (INT_MAX, INT_MAX + 1, INT_MAX - 1, 2 ** 53 + 1, 10 ** 18, 10 ** 19 - 1, 10 ** 19):
        for _ in range(6):
            extra = digits(rng, rng.randrange(0, 6), False)
            texts.append(spell(rng, str(limit) + extra, -len(extra)))
    while len(texts) < COUNT:
        length = rng.choice([1, 2, 5, 17, 18, 19, 19, 20, 21, 30, 40])
        significant = digits(rng, length, True)
        # most results have 15 to 21 digits before the point; some are tiny or huge
        target = rng.choice([0, 1, 5, 15, 17, 18, 19, 19, 19, 20, 21, 25, 60])
        point_shift = target - length + rng.randrange(-1, 2)
        texts.append(spell(rng, significant, point_shift))
    return texts


def render():
    rows = []
    for text in cases():
        rows.append('\t\t\t"{}", "{}"'.format(text, expected(text)))
    return """# GENERATED by gen_json_int_reference.py: do not edit, regenerate (the script's --check
# compares this file with what it would write).
#
# JsonElement->GetInt() against exact integer arithmetic: {count} numbers written with a
# fraction or an exponent, each with the value Python's unbounded integers give for its
# truncation toward zero (0 when that does not fit a signed 64-bit integer). The numbers
# are random with a fixed seed and are drawn around the places the conversion can go
# wrong: the 64-bit limits, fractions and exponents that cancel, runs of zeros on either
# side of the point. json_number_grammar holds the hand-written cases.

use Data.JSON;

class JsonIntReference {{
	function : Main(args : String[]) ~ Nil {{
		# text, expected
		cases := [
{rows}];

		failures := 0;
		for(i := 0; i < cases->Size(); i += 2;) {{
			text := cases[i];
			want := cases[i + 1];
			elem := JsonParser->TextToElement(text);
			if(elem = Nil) {{
				"  FAIL: '{{$text}}' did not parse"->PrintLine();
				failures += 1;
			}}
			else {{
				got := elem->GetInt()->ToString();
				if(<>got->Equals(want)) {{
					"  FAIL: '{{$text}}'->GetInt() = {{$got}}, expected {{$want}}"->PrintLine();
					failures += 1;
				}};
			}};
		}};

		count := cases->Size() / 2;
		if(failures = 0) {{
			"PASS: JSON GetInt against {{$count}} exact references"->PrintLine();
		}}
		else {{
			"FAIL: JSON GetInt against exact references ({{$failures}} of {{$count}})"->PrintLine();
			Runtime->Exit(1);
		}};
	}}
}}
""".format(count=COUNT, rows=",\n".join(rows))


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("stale: {} (run gen_json_int_reference.py)".format(OUT.name))
            return 1
        print("{} is current ({} cases)".format(OUT.name, COUNT))
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote {} ({} cases)".format(OUT.name, COUNT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
